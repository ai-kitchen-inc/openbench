-- Business schema + base seed for the db_server MCP (Cloud SQL Postgres, appdata).
--
-- Run `deploy.sh init-appdb` first (creates appdata + mart + mcp_app), then:
--     bash deploy/deploy.sh seed-mcp-db deploy/appdb/init.sql
--
-- Idempotent: drops + recreates the public business tables so re-seeding is clean.
-- Applied as the admin role; grants read to mcp_app at the end.

DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE products (
    id       integer PRIMARY KEY,
    name     text    NOT NULL,
    category text    NOT NULL,
    price    numeric(10, 2) NOT NULL,
    in_stock boolean NOT NULL DEFAULT true
);

